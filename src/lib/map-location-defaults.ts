import type { MapLocation, MapLocations } from '@/lib/map-location-service'

type LocationSeed = [name: string, xPct: number, yPct: number, diameterPct: number]

function locationId(name: string) {
  return name
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
}

function buildMapLocations(mapName: string, seeds: LocationSeed[]): MapLocation[] {
  return seeds.map(([name, xPct, yPct, diameterPct]) => ({
    id: `${mapName.toLowerCase()}-${locationId(name)}`,
    name,
    mapName,
    xPct,
    yPct,
    radiusPct: diameterPct / 2,
    enabled: true,
  }))
}

